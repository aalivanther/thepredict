/* ThePredict docs · theme switch, mobile navigation, copy buttons, table-of-contents highlight and local search.
   No network and no modules: works from file:// and over http. The search index is a script
   (assets/search-index.js, generated by tools/build.py) loaded on first use. */
(function () {
  "use strict";

  var root = document.documentElement;
  var body = document.body;

  function store(key, value) {
    try { if (value === null) { localStorage.removeItem(key); } else { localStorage.setItem(key, value); } } catch (e) { /* storage blocked */ }
  }

  /* ---------------------------------------------------------------- theme */
  var themeButton = document.getElementById("theme-btn");
  function currentTheme() {
    var set = root.getAttribute("data-theme");
    if (set === "light" || set === "dark") { return set; }
    return window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
  }
  function labelTheme() {
    if (!themeButton) { return; }
    var next = currentTheme() === "dark" ? "light" : "dark";
    themeButton.setAttribute("aria-label", "Switch to " + next + " theme");
    themeButton.setAttribute("title", "Switch to " + next + " theme");
  }
  if (themeButton) {
    themeButton.addEventListener("click", function () {
      var next = currentTheme() === "dark" ? "light" : "dark";
      root.setAttribute("data-theme", next);
      store("tp-docs-theme", next);
      labelTheme();
    });
    labelTheme();
  }

  /* ---------------------------------------------------------------- mobile navigation */
  var menuButton = document.getElementById("menu-btn");
  var sidebar = document.getElementById("sidebar");
  var scrim = document.getElementById("scrim");
  function setNav(open) {
    body.classList.toggle("nav-open", open);
    if (menuButton) {
      menuButton.setAttribute("aria-expanded", open ? "true" : "false");
      menuButton.setAttribute("aria-label", open ? "Close navigation" : "Open navigation");
    }
    if (scrim) { scrim.hidden = !open; }
    if (open && sidebar) {
      var current = sidebar.querySelector("a.is-current") || sidebar.querySelector("a");
      if (current) { current.focus({ preventScroll: true }); current.scrollIntoView({ block: "center" }); }
    }
  }
  if (menuButton) { menuButton.addEventListener("click", function () { setNav(!body.classList.contains("nav-open")); }); }
  if (scrim) { scrim.addEventListener("click", function () { setNav(false); }); }
  if (sidebar) {
    sidebar.addEventListener("click", function (event) {
      if (event.target.closest("a")) { setNav(false); }
    });
    var currentLink = sidebar.querySelector("a.is-current");
    if (currentLink && window.matchMedia("(min-width: 901px)").matches) {
      var top = currentLink.offsetTop - sidebar.clientHeight / 3;
      if (top > 0) { sidebar.scrollTop = top; }
    }
  }

  /* ---------------------------------------------------------------- copy buttons */
  function copyText(text, done) {
    function fallback() {
      var area = document.createElement("textarea");
      area.value = text;
      area.setAttribute("readonly", "");
      area.style.position = "fixed";
      area.style.top = "-1000px";
      document.body.appendChild(area);
      area.select();
      var ok = false;
      try { ok = document.execCommand("copy"); } catch (e) { ok = false; }
      document.body.removeChild(area);
      done(ok);
    }
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard.writeText(text).then(function () { done(true); }, fallback);
    } else {
      fallback();
    }
  }
  Array.prototype.forEach.call(document.querySelectorAll(".code"), function (block) {
    var head = block.querySelector(".code-head");
    var pre = block.querySelector("pre");
    if (!head || !pre) { return; }
    var button = document.createElement("button");
    button.type = "button";
    button.className = "copy-btn";
    button.textContent = "Copy";
    button.setAttribute("aria-label", "Copy code to clipboard");
    button.addEventListener("click", function () {
      copyText(pre.textContent, function (ok) {
        button.textContent = ok ? "Copied" : "Press Ctrl+C";
        button.classList.toggle("is-done", ok);
        if (!ok) {
          var range = document.createRange();
          range.selectNodeContents(pre);
          var selection = window.getSelection();
          selection.removeAllRanges();
          selection.addRange(range);
        }
        setTimeout(function () { button.textContent = "Copy"; button.classList.remove("is-done"); }, 1600);
      });
    });
    head.appendChild(button);
  });

  /* ---------------------------------------------------------------- table of contents */
  var tocLinks = Array.prototype.slice.call(document.querySelectorAll(".toc a"));
  if (tocLinks.length && "IntersectionObserver" in window) {
    var byId = {};
    tocLinks.forEach(function (link) { byId[decodeURIComponent(link.getAttribute("href").slice(1))] = link; });
    var headings = Array.prototype.slice.call(document.querySelectorAll(".doc h2[id], .doc h3[id]"))
      .filter(function (heading) { return byId[heading.id]; });
    var visible = {};
    var observer = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) { visible[entry.target.id] = entry.isIntersecting; });
      var active = null;
      for (var i = 0; i < headings.length; i++) {
        if (visible[headings[i].id]) { active = headings[i].id; break; }
      }
      if (!active) {
        for (var j = headings.length - 1; j >= 0; j--) {
          if (headings[j].getBoundingClientRect().top < 120) { active = headings[j].id; break; }
        }
      }
      tocLinks.forEach(function (link) { link.classList.remove("is-active"); });
      if (active && byId[active]) { byId[active].classList.add("is-active"); }
    }, { rootMargin: "-64px 0px -55% 0px" });
    headings.forEach(function (heading) { observer.observe(heading); });
  }

  /* ---------------------------------------------------------------- search */
  var input = document.getElementById("search-input");
  var results = document.getElementById("search-results");
  if (!input || !results) { return; }
  var index = null;
  var loading = false;
  var waiting = [];
  var active = -1;
  var shown = [];

  function loadIndex(then) {
    if (index) { then(); return; }
    waiting.push(then);
    if (loading) { return; }
    loading = true;
    if (window.TP_SEARCH) { prepare(); return; }
    var script = document.createElement("script");
    script.src = "assets/search-index.js";
    script.onload = prepare;
    script.onerror = function () {
      loading = false;
      results.innerHTML = '<p class="sr-empty">The search index could not be loaded.</p>';
      results.hidden = false;
    };
    document.head.appendChild(script);
  }
  function fold(text) {
    return String(text || "").toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
  }
  function prepare() {
    index = (window.TP_SEARCH || []).map(function (entry) {
      return { t: entry.t, p: entry.p, u: entry.u, x: entry.x || "", k: entry.k || "section",
               ft: fold(entry.t), fx: fold(entry.x), fp: fold(entry.p) };
    });
    var queue = waiting;
    waiting = [];
    queue.forEach(function (callback) { callback(); });
  }
  function terms(query) {
    return fold(query).split(/[\s,;]+/).map(function (term) { return term.replace(/^[<"'(]+|[>"'):]+$/g, ""); })
      .filter(function (term) { return term.length > 0; });
  }
  function score(entry, words) {
    var total = 0;
    for (var i = 0; i < words.length; i++) {
      var word = words[i];
      var inTitle = entry.ft.indexOf(word);
      if (inTitle >= 0) {
        total += 12;
        if (inTitle === 0) { total += 6; }
        if (entry.ft === word) { total += 14; }
        var lastDot = entry.ft.lastIndexOf(".");
        if (lastDot >= 0 && entry.ft.indexOf(word, lastDot) > lastDot) { total += 4; }
      } else if (entry.fx.indexOf(word) >= 0) {
        total += 3;
        var count = entry.fx.split(word).length - 1;
        total += Math.min(count, 4) - 1;
      } else if (entry.fp.indexOf(word) >= 0) {
        total += 1;
      } else {
        return 0;
      }
    }
    if (entry.k === "page") { total += 2; }
    return total;
  }
  function escapeHtml(text) {
    return String(text).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; });
  }
  function mark(text, words) {
    var html = escapeHtml(text);
    words.slice().sort(function (a, b) { return b.length - a.length; }).forEach(function (word) {
      if (word.length < 2) { return; }
      var safe = escapeHtml(word).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      html = html.replace(new RegExp("(" + safe + ")(?![^<]*>)", "ig"), "<mark>$1</mark>");
    });
    return html;
  }
  function snippet(entry, words) {
    var text = entry.x;
    if (!text) { return ""; }
    var folded = entry.fx;
    var at = -1;
    for (var i = 0; i < words.length && at < 0; i++) { at = folded.indexOf(words[i]); }
    var start = Math.max(0, at < 0 ? 0 : at - 60);
    var cut = text.slice(start, start + 170);
    return (start > 0 ? "…" : "") + cut + (start + 170 < text.length ? "…" : "");
  }
  function render(query) {
    var words = terms(query);
    active = -1;
    if (!words.length) { close(); return; }
    var found = [];
    for (var i = 0; i < index.length; i++) {
      var value = score(index[i], words);
      if (value > 0) { found.push({ entry: index[i], value: value }); }
    }
    found.sort(function (a, b) { return b.value - a.value || a.entry.t.length - b.entry.t.length; });
    shown = found.slice(0, 14).map(function (item) { return item.entry; });
    if (!shown.length) {
      results.innerHTML = '<p class="sr-empty">No results for “' + escapeHtml(query) + '”.</p>';
    } else {
      var head = '<p class="sr-head">' + found.length + (found.length === 1 ? " result" : " results") +
        (found.length > shown.length ? ", showing the best " + shown.length : "") + "</p>";
      results.innerHTML = head + shown.map(function (entry, position) {
        var kind = entry.k === "section" ? "" : '<span class="sr-kind">' + escapeHtml(entry.k) + "</span>";
        return '<a class="sr-item" role="option" id="sr-' + position + '" href="' + escapeHtml(entry.u) + '">' +
          '<span class="sr-title"><span class="sr-name">' + mark(entry.t, words) + "</span>" + kind + "</span>" +
          '<span class="sr-page">' + escapeHtml(entry.p) + "</span>" +
          '<span class="sr-snip">' + mark(snippet(entry, words), words) + "</span></a>";
      }).join("");
    }
    results.hidden = false;
    input.setAttribute("aria-expanded", "true");
  }
  function close() {
    results.hidden = true;
    input.setAttribute("aria-expanded", "false");
    input.removeAttribute("aria-activedescendant");
    active = -1;
  }
  function move(step) {
    var items = results.querySelectorAll(".sr-item");
    if (!items.length) { return; }
    active = (active + step + items.length) % items.length;
    Array.prototype.forEach.call(items, function (item, position) { item.classList.toggle("is-active", position === active); });
    items[active].scrollIntoView({ block: "nearest" });
    input.setAttribute("aria-activedescendant", items[active].id);
  }
  function go(link) {
    var target = link.getAttribute("href");
    close();
    var here = location.pathname.split("/").pop() || "index.html";
    var page = target.split("#")[0];
    if (page === here && target.indexOf("#") >= 0) {
      location.hash = target.slice(target.indexOf("#"));
      input.blur();
    } else {
      location.href = target;
    }
  }
  var timer = null;
  input.addEventListener("input", function () {
    var query = input.value;
    clearTimeout(timer);
    timer = setTimeout(function () { loadIndex(function () { render(query); }); }, 60);
  });
  input.addEventListener("focus", function () {
    loadIndex(function () { if (input.value.trim()) { render(input.value); } });
  });
  input.addEventListener("keydown", function (event) {
    if (event.key === "ArrowDown") { event.preventDefault(); move(1); }
    else if (event.key === "ArrowUp") { event.preventDefault(); move(-1); }
    else if (event.key === "Enter") {
      var items = results.querySelectorAll(".sr-item");
      if (items.length) { event.preventDefault(); go(items[active >= 0 ? active : 0]); }
    } else if (event.key === "Escape") {
      if (!results.hidden) { close(); } else { input.value = ""; input.blur(); }
    }
  });
  results.addEventListener("click", function (event) {
    var link = event.target.closest(".sr-item");
    if (link) { event.preventDefault(); go(link); }
  });
  document.addEventListener("click", function (event) {
    if (!event.target.closest(".search")) { close(); }
  });
  document.addEventListener("keydown", function (event) {
    var typing = /^(INPUT|TEXTAREA|SELECT)$/.test(document.activeElement && document.activeElement.tagName);
    if ((event.key === "/" && !typing) || ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === "k")) {
      event.preventDefault();
      input.focus();
      input.select();
    } else if (event.key === "Escape" && body.classList.contains("nav-open")) {
      setNav(false);
      if (menuButton) { menuButton.focus(); }
    }
  });
  // Support ?q= in the URL: open the search with that query.
  var match = /[?&]q=([^&]+)/.exec(location.search);
  if (match) {
    input.value = decodeURIComponent(match[1].replace(/\+/g, " "));
    loadIndex(function () { render(input.value); });
  }
})();
