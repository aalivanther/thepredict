package akyrion.thepredict.domain;

/**
 * Family of an {@link EnemyPattern} (M26.4). English names stand for the plan's Ritmo, Movimiento, Defensa, Avisos,
 * Recursos and Distancia.
 */
public enum PatternGroup {
    /** Rhythm of strikes. */
    RHYTHM,
    /** Footwork. */
    MOVEMENT,
    /** Shield habits. */
    DEFENSE,
    /** Answers to tells and area. */
    TELLS,
    /** Healing, pearls and totems. */
    RESOURCES,
    /** Range and height. */
    DISTANCE
}
